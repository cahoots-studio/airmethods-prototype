#!/usr/bin/env node
/**
 * Bootstrap a client theme from what a brand actually hands you.
 *
 *   npm run theme:new -- acme \
 *     --light="#FFFFFF" --dark="#111318" \
 *     --accent="Coral:#FF5A5F" --accent="Deep Sea:#0B5F6B"
 *
 * Brands do not arrive as a tidy set of scales. They arrive as a light colour
 * used for backgrounds, a dark colour used for text, and one or more accents.
 * That maps onto two different generators:
 *
 *   light + dark  -> neutral scale, interpolated between the two ends
 *   each accent   -> ramp radiating from the key
 *
 * Typography is copied from an existing theme, since a brand's typefaces are a
 * separate decision from its colours and there is nothing to derive.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { TOKENS_DIR, listThemes } from './lib/tokens.mjs';
import { rampFromKey, scaleBetween, lightnessOf } from './lib/color.mjs';

const args = process.argv.slice(2);
const flags = args.filter((a) => a.startsWith('--'));
const positional = args.filter((a) => !a.startsWith('--'));
const opt = (n, d) => {
  const f = flags.find((x) => x.startsWith(`--${n}=`));
  return f ? f.slice(n.length + 3).replace(/^["']|["']$/g, '') : d;
};
const all = (n) =>
  flags.filter((x) => x.startsWith(`--${n}=`)).map((x) => x.slice(n.length + 3).replace(/^["']|["']$/g, ''));

const name = positional[0];
const light = opt('light');
const dark = opt('dark');
const accents = all('accent');
const from = opt('from', listThemes()[0]);
const dry = flags.includes('--dry');

if (!name || !light || !dark || !accents.length) {
  console.error('\nUsage:');
  console.error('  npm run theme:new -- <name> --light="#hex" --dark="#hex" \\');
  console.error('    --accent="Name:#hex" [--accent="Name:#hex" …] [--from=<theme>] [--dry]\n');
  console.error('Example:');
  console.error('  npm run theme:new -- acme --light="#FFFFFF" --dark="#111318" \\');
  console.error('    --accent="Coral:#FF5A5F"\n');
  process.exit(1);
}

const target = join(TOKENS_DIR, 'themes', `${name}.json`);
if (existsSync(target) && !dry && !flags.includes('--force')) {
  console.error(`\n✗ tokens/themes/${name}.json already exists. --force to overwrite.\n`);
  process.exit(1);
}

const base = JSON.parse(readFileSync(join(TOKENS_DIR, 'themes', `${from}.json`), 'utf8'));

const color = { white: light };
Object.assign(color, scaleBetween('Neutral', light, dark));
color.black = dark;

const accentNames = [];
for (const spec of accents) {
  const i = spec.lastIndexOf(':');
  if (i < 1) {
    console.error(`\n✗ --accent must be "Name:#hex", got "${spec}"\n`);
    process.exit(1);
  }
  const label = spec.slice(0, i).trim();
  const key = spec.slice(i + 1).trim();
  accentNames.push(label);
  Object.assign(color, rampFromKey(label, key, { light, dark }));
}

for (const signal of ['success', 'warning', 'error']) {
  color[signal] = base.color?.[signal]?.$value ?? '#000000';
}

const doc = {
  $description:
    `${name} theme. Neutrals interpolated between the brand light and dark ends; ` +
    `accents radiated from their key colours. Generated by theme:new — every stop ` +
    `is hand-tunable from here, and color:add will refuse to overwrite them.`,
  $theme: name,
  color: Object.fromEntries(Object.entries(color).map(([k, v]) => [k, { $type: 'color', $value: v }])),
  opacity: base.opacity,
  family: base.family,
  'font-size': base['font-size'],
  weight: base.weight,
  leading: base.leading,
  tracking: base.tracking,
};

console.log(`\n${name}   light ${light}  dark ${dark}\n`);
console.log('  Neutral scale');
for (const [k, v] of Object.entries(color)) {
  if (!k.startsWith('neutral') && k !== 'white' && k !== 'black') continue;
  console.log(`    ${k.padEnd(26)} ${v}   L ${lightnessOf(v)}`);
}
for (const label of accentNames) {
  const slug = label.toLowerCase().replace(/\s+/g, '-');
  console.log(`\n  ${label}`);
  for (const [k, v] of Object.entries(color)) {
    if (k === slug || k.startsWith(slug + '-')) console.log(`    ${k.padEnd(26)} ${v}   L ${lightnessOf(v)}`);
  }
}

if (dry) {
  console.log('\n(--dry: nothing written)\n');
  process.exit(0);
}

writeFileSync(target, JSON.stringify(doc, null, 2) + '\n');
console.log(`\n✓ tokens/themes/${name}.json`);
console.log(`  ${Object.keys(color).length} colours · typography copied from ${from}`);
console.log('\n  Next: point the schemes at the new accent, then npm run tokens:build');
console.log(`  Schemes reference {color.<accent-slug>} — see tokens/schemes.json\n`);
