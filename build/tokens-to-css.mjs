#!/usr/bin/env node
/**
 * tokens -> dist/supercomponent.tokens.css
 *
 * Emits: :root custom properties + the Client-First structural utility classes
 * that are mechanically derivable from tokens (spacing, containers, text styles).
 * Hand-authored CF classes live in src/styles/base.css.
 */
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadRawMerged, resolveMap, listModes, cssVarName, listThemes, loadSchemes, resolveScheme, expandSchemes } from './lib/tokens.mjs';

const DIST = fileURLToPath(new URL('../dist/', import.meta.url));

const SECTION_SIZES = ['small', 'medium', 'large'];
const CONTAINERS = ['small', 'medium', 'large', 'full'];

const FONT_STACKS = (() => {
  try { const j = JSON.parse(readFileSync(new URL('../tokens/font-stacks.json', import.meta.url), 'utf8')); delete j.$description; return j; }
  catch { return {}; }
})();

const TEXT_STYLES = JSON.parse(
  readFileSync(new URL('../tokens/textstyles.json', import.meta.url), 'utf8')
);
const HEADING_DEFAULTS = TEXT_STYLES.$headingDefaults ?? {};
const styleNames = Object.keys(TEXT_STYLES).filter((k) => !k.startsWith('$'));

function textStyleRule(name, indent = '  ') {
  const s = TEXT_STYLES[name];
  // size and weight are variables; leading and tracking are literal, because
  // they are functions of size rather than scales in their own right.
  return [
    `${indent}font-family: var(--sc-typeface-family-${s.family});`,
    `${indent}font-size: var(--sc-${s.size.replace(/\./g, '-')});`,
    `${indent}font-weight: var(--sc-typeface-weight-${s.weight});`,
    `${indent}line-height: ${s.leading};`,
    `${indent}letter-spacing: ${s.tracking};`,
    ...(s.case ? [`${indent}text-transform: ${s.case};`] : []),
  ].join('\n');
}

/**
 * Modes mirror Webflow's seven breakpoints. Direction differs either side of
 * the base: the larger ones are min-width and cascade up, the smaller ones are
 * max-width and cascade down.
 *
 * `order` controls emission sequence, which decides the winner when two queries
 * both match. Ascending min-widths so 1920 beats 1440; descending max-widths so
 * portrait beats tablet. The two groups can never both match, so they do not
 * compete with each other.
 */
const MODES = {
  default: { dir: null, bp: null, order: 0 },
  wide: { dir: 'min', bp: 'breakpoint.wide', order: 1 },
  xwide: { dir: 'min', bp: 'breakpoint.xwide', order: 2 },
  tablet: { dir: 'max', bp: 'breakpoint.tablet', order: 3 },
  landscape: { dir: 'max', bp: 'breakpoint.landscape', order: 4 },
  portrait: { dir: 'max', bp: 'breakpoint.portrait', order: 5 },
};

function mediaFor(mode, t) {
  const m = MODES[mode];
  if (!m || !m.dir) return null;
  const value = t[m.bp]?.value;
  if (!value) throw new Error(`mode "${mode}" needs ${m.bp} defined in primitive.json`);
  return `@media (${m.dir}-width: ${value})`;
}

const modeOrder = (mode) => MODES[mode]?.order ?? 99;

function buildTheme(theme) {
  const raw = loadRawMerged(theme);
  const base = resolveMap(raw, 'default');
  const modes = listModes(raw).sort((a, b) => modeOrder(a) - modeOrder(b));

  const unknown = modes.filter((m) => !(m in MODES));
  if (unknown.length) {
    throw new Error(`unknown mode(s) in tokens: ${unknown.join(', ')} — add them to MODES`);
  }

  const blocks = modes.map((mode) => {
    const t = resolveMap(raw, mode);
    // A mode block carries ONLY what it actually overrides — everything else cascades.
    const entries = Object.entries(t).filter(([, v]) => mode === 'default' || v.overridden);
    return {
      mode,
      media: mediaFor(mode, base),
      count: entries.length,
      decls: entries
        .map(([path, { value }]) => {
          // Stored 0–1 so Figma can bind layer opacity; emitted as a percentage
          // so it drops straight into color-mix() without calc().
          let v = path.startsWith('opacity.') ? `${value}%` : value;
          // Figma family names are not web font names; map through font-stacks.json.
          if (path.startsWith('typeface.family.')) v = FONT_STACKS[value] ?? `"${value}"`;
          return `  ${cssVarName(path)}: ${v};`;
        })
        .join('\n'),
    };
  });

  return { theme, blocks, tokens: base, modes };
}

function emit() {
  const themes = listThemes();
  const built = themes.map(buildTheme);
  const primary = built[0];

  const out = [];
  out.push('/* GENERATED by build/tokens-to-css.mjs — do not edit. */');
  out.push('@layer sc-tokens, sc-base, sc-components, sc-utilities;\n');
  out.push('@layer sc-tokens {');
  for (const blk of primary.blocks) {
    if (!blk.count) continue;
    if (blk.media) out.push(`${blk.media} {\n:root {\n${blk.decls}\n}\n}\n`);
    else out.push(':root {\n' + blk.decls + '\n}\n');
  }
  for (const b of built.slice(1)) {
    for (const blk of b.blocks) {
      if (!blk.count) continue;
      const sel = `[data-sc-theme="${b.theme}"]`;
      if (blk.media) out.push(`${blk.media} {\n${sel} {\n${blk.decls}\n}\n}\n`);
      else out.push(`${sel} {\n${blk.decls}\n}\n`);
    }
  }
  out.push('}\n');

  // --- Color schemes (sc-tokens) ---
  // Each scheme is a complete role set. Two axes: data-sc-scheme varies
  // section to section, data-sc-mode is the light/dark toggle.
  const schemeDef = loadSchemes();
  let schemeCount = 0;
  if (schemeDef) {
    const raw = loadRawMerged(themes[0]);
    const DEFAULT = schemeDef.$default ?? 'default';
    const BASEMODE = schemeDef.$defaultMode ?? 'light';
    const roles = schemeDef.$roles ?? [];

    const expanded = expandSchemes(schemeDef);
    const sc = ['@layer sc-tokens {'];
    sc.push(`[data-sc-scheme], [data-sc-mode] { background-color: var(--sc-color-background); color: var(--sc-color-text); }\n`);
    for (const [name, byMode] of Object.entries(expanded)) {
      for (const mode of schemeDef.$modes ?? [BASEMODE]) {
        const set = byMode[mode];
        if (!set) continue;
        const overrides = Object.fromEntries(roles.map((r) => [`color.${r}`, set[r]]));
        const resolved = resolveScheme(raw, overrides, 'default');
        const decls = roles
          .map((r) => `  ${cssVarName(`color.${r}`)}: ${resolved[`color.${r}`].value};`)
          .join('\n');

        // The default scheme is :root in light mode and [data-sc-mode] in dark,
        // but it is ALSO emitted under its own attribute, so an element can switch
        // back to it inside another scheme (a white card in a navy hero). Without
        // this, nesting only ever works away from the default, never back to it.
        const explicit = `[data-sc-scheme="${name}"]`;
        const sels = [];
        if (name === DEFAULT) {
          if (mode !== BASEMODE) sels.push(`[data-sc-mode="${mode}"]`);
          sels.push(mode === BASEMODE ? explicit : `[data-sc-mode="${mode}"] ${explicit}`);
        } else {
          sels.push(mode === BASEMODE ? explicit : `[data-sc-mode="${mode}"] ${explicit}`);
        }
        for (const sel of sels) { sc.push(`${sel} {\n${decls}\n}\n`); schemeCount++; }
      }
    }
    sc.push('}\n');
    if (schemeCount) out.push(sc.join('\n'));
  }

  // --- Bare heading defaults (sc-base) ---
  // CMS content produces unclassed <h2> etc. These give them sensible sizes.
  // Anything with a .text-style-* class overrides, because utilities layer later.
  const h = ['@layer sc-base {'];
  for (const [tag, style] of Object.entries(HEADING_DEFAULTS)) {
    if (tag.startsWith('$')) continue;
    h.push(`${tag} {`);
    h.push(textStyleRule(style));
    h.push('}');
  }
  h.push('}\n');
  out.push(h.join('\n'));

  // --- Client-First utilities, derived from tokens ---
  const u = [];
  u.push('@layer sc-utilities {\n');

  u.push('/* Section padding */');
  for (const size of SECTION_SIZES) {
    u.push(`.padding-section-${size} {`);
    u.push(`  padding-top: var(--sc-padding-section-${size});`);
    u.push(`  padding-bottom: var(--sc-padding-section-${size});`);
    u.push('}');
  }

  u.push('\n/* Global horizontal padding */');
  u.push('.padding-global {');
  u.push('  padding-left: var(--sc-padding-section-global);');
  u.push('  padding-right: var(--sc-padding-section-global);');
  u.push('}');

  u.push('\n/* Containers */');
  for (const c of CONTAINERS) {
    u.push(`.container-${c} { width: 100%; max-width: var(--sc-width-container-${c}); margin-inline: auto; }`);
  }

  u.push('\n/* Spacer utilities */');
  for (const key of ['tiny', 'small', 'medium', 'large', 'huge']) {
    u.push(`.spacer-${key} { padding-top: var(--sc-padding-gap-${key}); }`);
  }

  u.push('\n/* Text styles — visual scale, independent of heading level */');
  for (const name of styleNames) {
    u.push(`.text-style-${name} {`);
    u.push(textStyleRule(name));
    u.push('}');
  }

  u.push('\n/* Text colour — the five roles, plus opacity steps for hierarchy */');
  for (const role of ['text', 'accent', 'background']) {
    u.push(`.text-color-${role} { color: var(--sc-color-${role}); }`);
  }
  u.push('.text-color-secondary { color: color-mix(in srgb, var(--sc-color-text) var(--sc-opacity-80), transparent); }');
  u.push('.text-color-muted { color: color-mix(in srgb, var(--sc-color-text) var(--sc-opacity-60), transparent); }');

  u.push('\n/* Surface colour */');
  for (const role of ['background', 'foreground', 'accent']) {
    u.push(`.background-color-${role} { background-color: var(--sc-color-${role}); }`);
  }
  u.push('.border-color-default { border-color: var(--sc-color-border); }');

  u.push('\n/* Column widths — tightest to widest */');
  const MW_SCALE = ['tightest', 'tighter', 'tight', 'medium', 'wide', 'wider', 'widest'];
  for (const step of MW_SCALE) {
    const path = primary.tokens[`width.column.${step}`] ? `width-column-${step}` :
      primary.tokens[`max-width.${step}`] ? `max-width-${step}` : null;
    if (path) {
      u.push(`.max-width-${step} { max-width: var(--sc-${path}); }`);
    }
  }

  u.push('\n/* Gap variants */');

  u.push('\n/* Alignment */');
  u.push('.text-align-center { text-align: center; }');
  u.push('.text-align-right { text-align: right; }');

  u.push('\n}');
  out.push(u.join('\n'));

  mkdirSync(DIST, { recursive: true });
  const css = out.join('\n') + '\n';
  writeFileSync(DIST + 'supercomponent.tokens.css', css);

  const count = Object.keys(primary.tokens).length;
  console.log(`✓ dist/supercomponent.tokens.css`);
  console.log(`  ${count} tokens · themes: ${themes.join(', ')}`);
  for (const blk of primary.blocks.filter((b) => b.mode !== 'default' && b.count)) {
    console.log(`  ${blk.mode}: ${blk.count} override(s) ${blk.media}`);
  }
  if (schemeCount) {
    const d = loadSchemes();
    const names = Object.keys(d?.schemes ?? {});
    console.log(`  schemes: ${names.join(', ')} · ${d.$roles.length} roles each · ${schemeCount} block(s)`);
  }
}

emit();
